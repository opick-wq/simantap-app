    private function row(string $gender, string $indikator, float $param,
                         float $L, float $M, float $S): array
    {
        return [
            'jenis_kelamin' => $gender,
            'indikator'     => $indikator,
            'parameter'     => $param,
            'l_value'       => $L,
            'm_value'       => $M,
            's_value'       => $S,
            'sd_minus3'     => $this->sd($L, $M, $S, -3),
            'sd_minus2'     => $this->sd($L, $M, $S, -2),
            'sd_minus1'     => $this->sd($L, $M, $S, -1),
            'median_val'    => round($M, 4),
            'sd_plus1'      => $this->sd($L, $M, $S, 1),
            'sd_plus2'      => $this->sd($L, $M, $S, 2),
            'sd_plus3'      => $this->sd($L, $M, $S, 3),
        ];
    }

    private function sd(float $L, float $M, float $S, int $z): float
    {
        if (abs($L) < 0.0001) {
            return round($M * exp($S * $z), 4);
        }
        return round($M * pow(1 + $L * $S * $z, 1 / $L), 4);
    }
