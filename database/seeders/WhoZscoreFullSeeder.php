    /** Hitung SD(-3 s.d. +3) dari nilai LMS menggunakan formula Cole & Green (1992) */
    private function sd(float $L, float $M, float $S, float $z): float
    {
        if (abs($L) < 0.0001) {
            return round($M * exp($S * $z), 4);
        }
        return round($M * pow(1 + $L * $S * $z, 1 / $L), 4);
    }

